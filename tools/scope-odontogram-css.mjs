// Scopes the odontogram library's stylesheet so it can't restyle the CRM.
// The library ships generic global selectors (.btn, .card, .row, body, *...). Everything is prefixed with
// `.odontogram-root`, except `.odon-*` (its popups, appended to <body> and already namespaced) and pure
// variable definitions. Rules for body/html/* are dropped: the CRM owns those.
// Usage: node tools/scope-odontogram-css.mjs   (writes src/odontogram.css)
import { readFileSync, writeFileSync } from 'node:fs';
import postcss from 'postcss';

const ROOT = '.odontogram-root';
const source = readFileSync('node_modules/angular-advanced-odontogram/styles.css', 'utf8');
const tree = postcss.parse(source);

tree.walkRules((rule) => {
  if (rule.parent?.type === 'atrule' && /keyframes$/.test(rule.parent.name)) return;
  const onlyVariables = rule.nodes.length > 0 && rule.nodes.every((n) => n.type === 'decl' && n.prop.startsWith('--'));
  const scoped = rule.selectors.flatMap((raw) => {
    const sel = raw.trim();
    if (sel.includes('odontogram-root') || /^(\.dark\s+)?\.odon-/.test(sel)) return [sel];
    if (/^(:root|html|body|\*)(\s|,|$|[.:#\[>+~])/.test(sel) || sel === '*') return onlyVariables && sel === ':root' ? [sel] : [];
    return [sel.startsWith('.dark ') ? `.dark ${ROOT} ${sel.slice(6)}` : `${ROOT} ${sel}`];
  });
  if (scoped.length) rule.selectors = scoped;
  else rule.remove();
});

writeFileSync('src/odontogram.css', `/* Generated by tools/scope-odontogram-css.mjs from angular-advanced-odontogram (MIT). Do not edit. */\n${tree.toString()}\n`);
console.log('wrote src/odontogram.css');
