"""Flat outlines of the 32 crowns, seen from the biting side, for the printed tooth chart.
Reads public/models/teeth (teeth.json + teeth.bin) and writes src/app/denteus/documents/tooth-outlines.ts.
Frame (mm, upper-arch picture): x runs along the arch with the mesial side on the right in quadrants 1 and 4 (left in 2 and 3);
y is negative toward the cheek or lip, so the cheek side is up. The lower arch is drawn by flipping y."""
import json, struct, sys
import numpy as np
from shapely.geometry import Polygon, MultiPolygon, box
from shapely.ops import unary_union

root = sys.argv[1] if len(sys.argv) > 1 else '.'
meta = json.load(open(f'{root}/public/models/teeth/teeth.json'))
buf = open(f'{root}/public/models/teeth/teeth.bin', 'rb').read()

def path(g):
    polys = list(g.geoms) if isinstance(g, MultiPolygon) else [g]
    out = []
    for p in polys:
        if p.is_empty or p.geom_type != 'Polygon': continue
        for ring in [p.exterior, *p.interiors]:
            c = list(ring.coords)[:-1]
            out.append('M' + 'L'.join(f'{x:.2f} {y:.2f}' for x, y in c) + 'Z')
    return ''.join(out)

res = {}
for p in meta['parts']:
    if p['kind'] != 'crown': continue
    n = p['vertexCount']
    pos = np.frombuffer(buf, dtype='<f4', count=n * 3, offset=p['pos']).reshape(n, 3)
    idx = np.frombuffer(buf, dtype='<u2', count=p['indexCount'], offset=p['idx']).reshape(-1, 3)
    fdi = p['fdi']; mesial_right = fdi < 20 or fdi >= 40
    sign = p['mesial'] * (1 if mesial_right else -1)
    pts = np.stack([pos[:, 0] * sign, -pos[:, 2]], axis=1)  # cheek side up
    tris = [Polygon(pts[t]) for t in idx if Polygon(pts[t]).area > 1e-6]
    shape = unary_union(tris).buffer(0.15).buffer(-0.15).simplify(0.07)
    if isinstance(shape, MultiPolygon): shape = max(shape.geoms, key=lambda g: g.area)
    shape = Polygon(shape.exterior)  # no holes
    minx, miny, maxx, maxy = shape.bounds
    cx, cy = (minx + maxx) / 2, (miny + maxy) / 2
    shape = Polygon([(x - cx, y - cy) for x, y in shape.exterior.coords])
    w, d = maxx - minx, maxy - miny
    inner = shape.buffer(-min(w, d) * 0.26)
    ring = shape.difference(inner)
    big = 100
    wedge = {'buccal': Polygon([(0, 0), (-big, -big), (big, -big)]), 'lingual': Polygon([(0, 0), (-big, big), (big, big)]),
             'left': Polygon([(0, 0), (-big, -big), (-big, big)]), 'right': Polygon([(0, 0), (big, -big), (big, big)])}
    mes, dis = ('right', 'left') if mesial_right else ('left', 'right')
    zones = {'occlusal': inner, 'buccal': ring.intersection(wedge['buccal']), 'lingual': ring.intersection(wedge['lingual']),
             'mesial': ring.intersection(wedge[mes]), 'distal': ring.intersection(wedge[dis])}
    res[fdi] = {'w': round(w, 2), 'd': round(d, 2), 'all': path(shape), **{k: path(v) for k, v in zones.items()}}

lines = ['// Generated by tools/tooth-lib/outlines.py from the 3D tooth library (CC BY-SA 4.0, see public/models/teeth/ATTRIBUTION.md). Do not edit.',
         'export interface Outline { w: number; d: number; all: string; occlusal: string; buccal: string; lingual: string; mesial: string; distal: string }',
         'export const OUTLINES: Record<number, Outline> = {']
for f in sorted(res): lines.append(f'  {f}: {json.dumps(res[f])},')
lines.append('};')
open(f'{root}/src/app/denteus/documents/tooth-outlines.ts', 'w').write('\n'.join(lines) + '\n')
print(len(res), 'teeth', sum(len(json.dumps(v)) for v in res.values()) // 1024, 'KB')
